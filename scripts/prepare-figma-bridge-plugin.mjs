import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const pluginId = process.argv[2]?.trim() || process.env.FIGMA_PLUGIN_ID?.trim();
if (!pluginId) throw new Error("Provide the development plugin id generated by Figma: node scripts/prepare-figma-bridge-plugin.mjs <FIGMA_PLUGIN_ID>");
if (!/^[A-Za-z0-9_-]+$/.test(pluginId)) throw new Error("Figma plugin id contains unexpected characters");

const dir = resolve("apps", "figma-bridge-plugin");
const template = await readFile(resolve(dir, "manifest.template.json"), "utf8");
const output = template.replace("__FIGMA_PLUGIN_ID__", pluginId);
if (output.includes("__FIGMA_PLUGIN_ID__")) throw new Error("Failed to inject Figma plugin id");
await writeFile(resolve(dir, "manifest.local.json"), output, "utf8");
console.log(`Prepared ${resolve(dir, "manifest.local.json")}`);
